        self.reduce_chan_level3 = nn.Conv2d(int(dim/2*3), int(dim), kernel_size=1, bias=bias)
        
        self.latent = nn.Sequential(*[TransformerBlock(dim=int(dim), num_heads=heads[3], ffn_expansion_factor=ffn_expansion_factor, bias=bias, LayerNorm_type=LayerNorm_type) for i in range(num_blocks[3])])
        
        self.decoder_level1 = nn.Sequential(*[TransformerBlock(dim=int(dim), num_heads=heads[2], ffn_expansion_factor=ffn_expansion_factor, bias=bias, LayerNorm_type=LayerNorm_type) for i in range(num_blocks[2])])
        
